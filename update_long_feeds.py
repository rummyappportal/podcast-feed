def update_xml_file(filepath, new_cdata):
    try:
        with open(filepath, 'r', encoding='utf-8') as f:
            content = f.read()
            
        # The regex looks for <![CDATA[ ... ]]> blocks inside <itunes:summary> and <description>
        # and replaces them entirely.
        
        # Replace inside itunes:summary
        content = re.sub(r'<itunes:summary><!\[CDATA\[.*?\]\]></itunes:summary>', 
                         f'<itunes:summary>{new_cdata}</itunes:summary>', 
                         content, flags=re.DOTALL)
                         
        # Replace inside description
        content = re.sub(r'<description><!\[CDATA\[.*?\]\]></description>', 
                         f'<description>{new_cdata}</description>', 
                         content, flags=re.DOTALL)
                         
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(content)
            
        print(f"Successfully updated {filepath}")
    except Exception as e:
        print(f"Error updating {filepath}: {e}")

